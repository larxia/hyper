static int32_t menu_text(const char *s, int32_t y, uint16_t col, int draw)
{
    while (*s) {
        char line[64];
        uint32_t n = 0, space = 0, take, prev = 0;
        int32_t pen = 0;                                 /* 1/16 px, as text_w adds it up */
        while (s[n] && n < sizeof line - 1u) {
            uint32_t c = (uint8_t)s[n];
            line[n] = s[n];
            line[n + 1u] = 0;
            pen += (prev ? kern(&AF_S, prev, c) : 0) + AF_S.g[glyph(&AF_S, c)].adv;
            prev = c;
            if ((pen + 8) >> 4 > 226)
                break;
            if (s[n] == ' ')
                space = n;
            n++;
        }
        take = s[n] && space ? space : n;
        if (!take) take = 1;                         /* progress even for an unusually wide glyph */
        line[take] = 0;
        if (draw && y + AF_S.h > 0 && y < MENU_DOC_H)
            cv_text(6, y, &AF_S, line, col);
        y += 18;
        s += take;
        while (*s == ' ') s++;
    }
    return y;
}

static int32_t menu_document(int32_t y, int draw)
{
    uint32_t i;
    if (draw) {
        cv_text(6, y + 2, &AF_L, FW_NAME, T_THEME);
        cv_text(6, y + 38, &AF_S, "based on Felucca", T_TEXT);
        cv_text(6, y + 58, &AF_M, FELUCCA_VERSION, T_THEME);
        cv_text_r(232, y + 61, &AF_S, __DATE__, T_MID, T_BG);
        cv_text(6, y + 82, &AF_S, "(C) 2026 Leo Kuroshita", T_TEXT);
        cv_text(6, y + 100, &AF_S, "H\xFCgelton Instruments", T_TEXT);
        cv_text(6, y + 118, &AF_S, "GPL-3.0-only", T_TEXT);
        cv_text(6, y + 138, &AF_S, "hugelton.github.io", T_MID);
        cv_text(6, y + 156, &AF_S, "/Felucca", T_MID);
        cv_text(6, y + 180, &AF_S, "hugelton.com", T_MID);
        draw_about_qr(158, y + 122);
    }
    y = menu_text("CREDITS", y + 216, T_THEME, draw) + 8;
    for (i = 0; i < NELEM(MENU_CREDITS); i++) {
        const menu_credit_t *c = &MENU_CREDITS[i];
        const char *text = c->text;
        /* Display host/path once; the full source URL stays in the flash table. */
        if (c->kind == MC_URL && str_len(text) >= 8u && !memcmp(text, "https://", 8))
            text += 8;
        if (!text[0]) y += 8;
        else y = menu_text(text, y, c->kind == MC_TITLE ? T_THEME : c->kind == MC_URL ? T_MID : T_TEXT, draw);
    }
    y = menu_text("LICENSES + SOURCE", y + 12, T_THEME, draw);
    y = menu_text("DRUM + own samples: GPL-3.0-only", y, T_TEXT, draw);
    y = menu_text("Fonts and icons: their licences travel with the source and the release files.", y, T_TEXT, draw);
    y = menu_text("NO WARRANTY", y, T_TEXT, draw);
    y = menu_text("Full notices in source:", y + 8, T_TEXT, draw);
    y = menu_text("github.com/hugelton/Felucca", y, T_MID, draw);
    return y + 4;
}
static int32_t menu_scroll_max(void)
{
    int32_t h = menu_document(0, 0);
    return h > MENU_DOC_H ? h - MENU_DOC_H : 0;
}

/* The page (1.0.5; Dah: one list, as SEQ's held menu; every menu alike):
 *   header   0..18  HOME's (ui_draw.c head_home): MENU, the pattern, the track, the load, the tempo, the battery
 *   cards           KNOB 1 the row (n/N), KNOB 2 its value (OCT- / OCT+ step it too), KNOB 3 and 4 none
 *   rows            the panel (graph_y, graph_h): every row of the old tabs DISPLAY CONTROL AUDIO MIDI SYSTEM one after
 *                   the other (MI_TAB: the editor's tabs; the device shows none), CALIBRATION INFO ABOUT at the end. The
 *                   shared list (ml_draw: GLO SEQ REC's too): a row a RAISE cushion, its label at the left (TEXT), its
 *                   value at the right (THEME); ON / OFF a switch, COLOR its palette's five colours, CALIBRATION, INFO,
 *                   ABOUT a chevron. The selected one framed (THEME, RAISE in it), in M, KNOB 2's cap before its value
 *                   (OCT+'s where it opens / clears); the others S. The frame from the top down to the middle, the rows
 *                   by under it, at the end on down (ui_graph.c tall_view); the rows cut by the panel's edges small and
 *                   faint; a scrollbar at the right (list_bar); ANIM ON: the rows glide (mr.dy)
 *   keys            the footer band (menu_foot): OCT- (HOLD) RESET SETTINGS, OCT+ OPEN / CLEAR. No knob there
 * The panel in two canvases (panel_bands), split in a gap; while the rows glide only they are drawn again */
#define MR_X 8                                         /* (INFO's rows) */
#define MR_W 224
#define MR_LX 16                                       /* a row's label */
#define MR_VR 224                                      /* (INFO's) value's right edge */
#define MP_PAD 3                                       /* the rows' room: the panel less this, top and foot */
static int menu_large(void) { return (ui_prefs & PREF_LARGE) != 0u; }
static uint32_t menu_tab(void) { return MI_TAB[ui.menu_sel % MI_COUNT]; }   /* (the editor's tab of the row picked) */
static int32_t mr_h(void) { return menu_large() ? 26 : 22; }   /* a row (2 px between two) */
/* the rows' glide (px still to go, as ui_graph.c glide: a quarter a frame); one list shows at a time: every list's */
static struct { int16_t dy, drawn; } mr;
static void ml_glide(uint32_t was, uint32_t now)      /* the row picked went from `was` to `now` */
{
    int32_t d = ((int32_t)now - (int32_t)was) * (mr_h() + 2);
    mr.dy = (ui_prefs & PREF_ANIM_OFF) ? 0 : (int16_t)clamp(mr.dy + d, -2 * (mr_h() + 2), 2 * (mr_h() + 2));
}
static void ml_tick(void)                              /* a step of the glide, a frame each */
{
    if (ui_prefs & PREF_ANIM_OFF)
        mr.dy = 0;
    else
        mr.dy = (int16_t)(mr.dy - (mr.dy / 4 ? mr.dy / 4 : mr.dy > 0 ? 1 : mr.dy < 0 ? -1 : 0));
}
/* the MENU's rows: every one in a tab (not MTAB_OFF: REC's, GLO's, the editor's), in their order */
static uint32_t menu_nvis(void)
{
    uint32_t i, n = 0;
    for (i = 0; i < MI_COUNT; i++)
        n += MI_TAB[i] < MTAB_COUNT;
    return n;
}
static uint32_t menu_vis(uint32_t k)                   /* the k-th shown row */
{
    uint32_t i;
    for (i = 0; i < MI_COUNT; i++)
        if (MI_TAB[i] < MTAB_COUNT && !k--)
            return i;
    return MI_COUNT - 1u;
}
static uint32_t menu_pos(uint32_t row)                 /* .. and a row's place among them */
{
    uint32_t i, n = 0;
    for (i = 0; i < row && i < MI_COUNT; i++)
        n += MI_TAB[i] < MTAB_COUNT;
    return n;
}
/* every menu's footer: its keys (no knob: the cards say them) in HOME's band at the screen's foot */
static void menu_foot(const khint_t *kh, uint32_t n, uint32_t ok)
{
    cv_begin(240, HOME_FOOT_H, T_BG);
    if (n)
        cv_key_row(4, 236, (HOME_FOOT_H - KC_H) / 2, kh, n, ok, T_BG);
    cv_blit(0, 240u - HOME_FOOT_H);
}
/* every menu's panel (graph_y, graph_h tall: taller than the canvas) in two canvases, the second from `split` (a gap
 * between two rows or cells: nothing cut); body draws in the panel's rows (cv_py) */
static void panel_bands(void (*body)(void), int32_t split)
{
    int32_t gh = (int32_t)graph_h(), pass;
    split = clamp(split, gh - (int32_t)(CV_MAX / 240u), (int32_t)(CV_MAX / 240u));
    for (pass = 0; pass < 2; pass++) {
        int32_t top = pass ? split : 0;
        cv_begin(240, (uint32_t)((pass ? gh : split) - top), T_BG);
        cv_split = 1;
        cv_split_h = gh;
        cv_py = -top;
        cv_rrect(3, 0, 234, gh, 5, T_SURF, T_BG);
        cv_bg = T_SURF;
        body();
        cv_py = 0;
        cv_split = 0;
        cv_blit(0, graph_y() + (uint32_t)top);
    }
}
/* a two-valued row whose values are ON and OFF: a switch (a 26 x 14 cushion, its knob at the right when ON) */
static void menu_switch(int32_t xr, int32_t y, int32_t h, int on)
{
    int32_t x = xr - 26, ty = y + HALF_UP(h - 14);
    uint16_t track = on ? T_THEME : T_DIM, knob = on ? T_INK : T_TEXT;
    cv_rrect(x, ty, 26, 14, -7, track, T_RAISE);
    cv_rrect(on ? x + 14 : x + 2, ty + 2, 10, 10, -5, knob, track);
}
/* menu_items.c row `row` on its cushion at y (h tall), its value's right edge xr; big: the one in the frame (M, its
 * key's cap); hk: whole in this canvas (the lint's hooks) */
static void menu_row(uint32_t row, int32_t y, int32_t h, int32_t xr, int big, int hk)
{
    const aafont_t *f = big || menu_large() ? &AF_M : &AF_S;
    int32_t vy = y + (f == &AF_M ? CAP_IN(M, h) : CAP_IN(S, h)), x = xr, le;
    uint16_t val = T_THEME;
    uint32_t kc = menu_valued(row) ? KC_K2 : KC_OCTUP;
    const char *v = menu_valued(row) ? menu_vname(row, menu_get(row)) : "";
    char b[8];
    if (MI_TCH(row) && song.g[G_ROUTE] != ROUTE_TRACK)
        val = T_MID;                                   /* (1.5.5: T1..T4 CHANNEL, unused but with MIDI IN TRACK) */
    if (hk) GFX_HOOK_ALIGN(0, y, 0, y + h, AL_V, "menu row name centred up/down");
    le = cv_text_on(MR_LX, vy, f, menu_label(row), T_TEXT, T_RAISE);
    if (row == MI_LCLEAR) {                            /* LEARN CLEAR (1.5): how many CCs are learned, "NONE" */
        str_cpy(b, "NONE", sizeof b);
        if (ml_count()) {
            fmt_int(b, (int32_t)ml_count());
            str_cpy(b + str_len(b), " CC", 4);
        }
        if (hk) GFX_HOOK_ALIGN(0, y, 0, y + h, AL_V, "menu row value centred up/down");
        x = cv_text_r(xr, vy, f, b, val, T_RAISE);
    } else if (row >= MI_VALUES) {                     /* CALIBRATION, INFO, ABOUT: OCT+ opens them */
        if (hk) GFX_HOOK_ALIGN(0, y, 0, y + h, AL_V, "menu row chevron centred up/down");
        cv_icon_in(xr - 12, y, 0, h, 12, ICON_X_RIGHT, T_MID, T_RAISE);
        x = xr - 12;
    } else if (row == MI_HOLD) {                       /* "0.4" s: the value and its unit */
        str_cpy(b, "0.4", sizeof b);
        b[2] = (char)('0' + HOLD_MS[settings_hold % 4u] / 100u);
        if (hk) GFX_HOOK_ALIGN(0, y, 0, y + h, AL_V, "menu row value centred up/down");
        if (hk) GFX_HOOK_ALIGN(0, 0, 0, vy + f->asc, AL_B, "menu row unit on its value's baseline");
        x = cv_text_r(cv_text_r(xr, vy + f->asc - AF_S.asc, &AF_S, "s", T_MID, T_RAISE) - 3, vy, f, b, val, T_RAISE);
    } else if (menu_n(row) == 2u && (str_eq(v, "ON") || str_eq(v, "OFF")) && !MI_TEXT(row)) {
        menu_switch(xr, y, h, str_eq(v, "ON"));
        x = xr - 26;
    } else if (row != MI_COLOR) {
        if (hk) GFX_HOOK_ALIGN(0, y, 0, y + h, AL_V, "menu row value centred up/down");
        x = cv_text_r(xr, vy, f, v, val, T_RAISE);
    } else {   /* COLOR: the palette's name and its five colours (BG SURF TEXT THEME ACCENT), live */
        uint32_t c;
        const uint16_t *tok = &T_BG;
        int32_t x0 = xr - 74, sy = y + HALF_UP(h - 12);
        if (hk) GFX_HOOK_ALIGN(0, y, 0, y + h, AL_V, "menu row value centred up/down");
        x = cv_text_r(x0 - 6, y + CAP_IN(S, h), &AF_S, v, val, T_RAISE);   /* (S: room for the cap) */
        for (c = 0; c < 5u; c++) {
            cv_rrect(x0 + (int32_t)c * 15, sy, 12, 12, -3, T_LINE, T_RAISE);       /* a rim for the dark ones */
            cv_rrect(x0 + 1 + (int32_t)c * 15, sy + 1, 10, 10, -2, tok[c], T_LINE);
        }
    }
    if (big && x - 6 - kc_w(kc) >= le + 6 && (menu_valued(row) || row >= MI_VALUES || row == MI_LCLEAR))   /* (as SEQ's: the knob's cap before it) */
        cv_keycap(x - 6 - kc_w(kc), y + (h - KC_H) / 2, kc, T_KEY, T_INK, T_RAISE);
}
/* MENU > SYSTEM > INFO (1.2, ui.menu 3): what the old GLO > SYSTEM page showed, read only: the firmware, the USB link (the
 * SYSTEM page's MIDI card: OFF no USB, WAIT no bus yet, BUS frames seen, ENUM being set up, MIDI in use) and the CPU load
 * of the audio (its SYSTEM card; the shown value follows every INFO_CPU_MS, not every frame). The rows as the menu's (no
 * tabs: from INFO_Y), the selected look on none; OCT- back to the tabs, HOME closes */
#define INFO_Y 32
#define INFO_N 4u
#define INFO_CPU_MS 500u
static struct { uint8_t cpu, peak; uint32_t t; } info;
static uint32_t info_usb(void)                         /* 0 OFF, 1 WAIT, 2 BUS, 3 ENUM, 4 MIDI */
{
    return !usb.up ? 0u : usb.config ? 4u : usb.setups ? 3u : usb.sof_seen ? 2u : 1u;
}
static uint32_t info_sig(void)
{
    if (fm1_ms - info.t >= INFO_CPU_MS) {
        info.t = fm1_ms;
        info.cpu = (uint8_t)(song.cpu_q8 * 100u / 256u);
        info.peak = (uint8_t)(song.cpu_peak_q8 * 100u / 256u > 255u ? 255u : song.cpu_peak_q8 * 100u / 256u);
        song.cpu_peak_q8 = 0;                           /* (Dah: the highest half of the last INFO_CPU_MS) */
    }
    return info.cpu * 7u + info.peak * 1031u + info_usb() * 131u + 1u;
}
static void info_rows(void)                            /* (in screen rows: cv_oy set by the caller) */
{
    static const char *const LBL[INFO_N] = {"FIRMWARE", "USB", "CPU", "CPU PEAK"};
    static const char *const USB_N[5] = {"OFF", "WAIT", "BUS", "ENUM", "MIDI"};
    int32_t h = menu_large() ? 28 : 24;
    uint32_t k;
    char cpu[8];
    if (!ux.style)                                     /* FLAT: the rows' panel */
        cv_rrect(4, INFO_Y, 232, (int32_t)INFO_N * (h + 2) - 2 + 2 * MP_PAD, 8, T_SURF, T_BG);
    for (k = 0; k < INFO_N; k++) {
        int32_t y = INFO_Y + MP_PAD + (int32_t)k * (h + 2), vy = y + CAP_IN(M, h);
        if (k)
            cv_rect(MR_X + 6, y - 1, MR_W - 12, 1, ux.style ? T_RULE : T_LINE);
        GFX_HOOK_ALIGN(0, y, 0, y + h, AL_V, "info row name centred up/down");
        cv_text_on(MR_LX, vy, &AF_M, LBL[k], T_TEXT, T_SURF);
        GFX_HOOK_ALIGN(0, y, 0, y + h, AL_V, "info row value centred up/down");
        if (k >= 2u) {                                 /* CPU, its PEAK: the value and its unit, as HOLD's */
            fmt_int(cpu, k == 2u ? info.cpu : info.peak);
            GFX_HOOK_ALIGN(0, 0, 0, vy + AF_M.asc, AL_B, "info row unit on its value's baseline");
            cv_text_r(cv_text_r(MR_VR, vy + AF_M.asc - AF_S.asc, &AF_S, "%", T_MID, T_SURF) - 3, vy, &AF_M, cpu, T_THEME, T_SURF);
        } else {
            cv_text_r(MR_VR, vy, &AF_M, k ? USB_N[info_usb()] : FELUCCA_VERSION, T_THEME, T_SURF);
        }
    }
}

/* (Dah) every list menu's list (MENU; GLO, SEQ, REC held: ui_layer.c), one renderer so they cannot drift: n rows,
 * sel the one picked, in the room y0 .. y1 (the panel's rows); paint(k, y, h, xr, big, hk) draws row k's label and
 * value on its cushion (xr: the value's right edge; big: in the frame, M and its key's cap; hk: whole in this canvas,
 * the lint's hooks), label(k) a row cut by the room's edges (small, faint). A list as the app's (ui_graph.c
 * tall_view): the frame from the top down to the middle, the rows by under it, at the end on down; ANIM ON the rows
 * glide (mr.dy); a scrollbar at the right (list_bar) when they do not all fit */
typedef void (*ml_paint_fn)(uint32_t k, int32_t y, int32_t h, int32_t xr, int big, int hk);
typedef const char *(*ml_label_fn)(uint32_t k);
static void ml_draw(ml_paint_fn paint, ml_label_fn label, uint32_t n, uint32_t sel, int32_t y0, int32_t y1)
{
    int32_t h = mr_h(), fy, k, ch = (int32_t)n * (h + 2) - 2;
    int32_t vt = tall_view((int32_t)n, (int32_t)sel, mr.dy, y1 - y0, &fy, h);
    int32_t w = ch > y1 - y0 ? 220 : 228, xr = 6 + w - 10, on;   /* (left of the scrollbar, when there is one) */
    uint16_t pb = T_SURF;
    int16_t c0 = cv_cy0, c1 = cv_cy1;
    fy = clamp(fy, 0, y1 - y0 - h);                   /* (a wrap's glide: the frame stays in the room) */
    cv_cy0 = (int16_t)clamp(y0 + CV_OY, 0, (int32_t)cv_h);   /* (the rows cut by the room's edges: clipped to it) */
    cv_cy1 = (int16_t)clamp(y1 + CV_OY, cv_cy0, (int32_t)cv_h);
    cv_scroll = 1;
    on = y0 + fy == y0 + (int32_t)sel * (h + 2) - vt;   /* (settled: the frame on its row) */
    for (k = 0; k < (int32_t)n; k++) {
        int32_t y = y0 + k * (h + 2) - vt;
        if (y + h <= y0 || y >= y1 || y + h + CV_OY <= 0 || y + CV_OY >= (int32_t)cv_h)
            continue;
        if (y < y0 || y + h > y1) {                     /* (cut: small, faint) */
            cv_text_on(MR_LX, y + CAP_IN(S, h), &AF_S, label((uint32_t)k), ux_mix(pb, T_MID, 55), pb);
            continue;
        }
        if (on && y == y0 + fy) {                       /* (the selected row: framed) */
            cv_rrect(6, y, w, h, 5, T_THEME, pb);
            cv_rrect(8, y + 2, w - 4, h - 4, 4, T_RAISE, T_THEME);
        } else
            cv_rrect(6, y, w, h, 5, T_RAISE, pb);         /* (a cushion each) */
        paint((uint32_t)k, y, h, xr, y > y0 + fy - h / 2 && y < y0 + fy + h / 2,   /* (near the frame: M) */
              y + CV_OY >= 0 && y + h + CV_OY <= (int32_t)cv_h);
    }
    if (!on) {                                         /* (gliding: the frame over the rows, an outline) */
        int32_t fy0 = y0 + fy;
        cv_rect(9, fy0, w - 6, 2, T_THEME);
        cv_rect(9, fy0 + h - 2, w - 6, 2, T_THEME);
        cv_rect(6, fy0 + 3, 2, h - 6, T_THEME);
        cv_rect(4 + w, fy0 + 3, 2, h - 6, T_THEME);
        for (k = 0; k < 2; k++) {
            cv_rect(7, k ? fy0 + h - 3 : fy0 + 1, 2, 2, T_THEME);
            cv_rect(3 + w, k ? fy0 + h - 3 : fy0 + 1, 2, 2, T_THEME);
        }
    }
    list_bar(y0, y1, ch, vt);
    cv_scroll = 0;
    cv_cy0 = c0;
    cv_cy1 = c1;
}
/* where the panel's two canvases meet (panel_bands): in the gap above a row of the list, never through one */
static int32_t ml_split(uint32_t n, uint32_t sel, int32_t y0, int32_t y1)
{
    int32_t h = mr_h(), fy, k, y, gh = (int32_t)graph_h(), mx = (int32_t)(CV_MAX / 240u);
    int32_t vt = tall_view((int32_t)n, (int32_t)sel, mr.dy, y1 - y0, &fy, h);
    for (k = 0; k <= (int32_t)n; k++)
        if ((y = y0 + k * (h + 2) - vt - 1) >= gh - mx && y >= gh / 3 && y <= mx)
            return y;
    return gh / 2;
}
