/* menu (Dah: as SEQ's held menu): KNOB 1 the row (one list, from the first of DISPLAY's to ABOUT; the ends stop it),
 * KNOB 2 or OCT+ / OCT- change its value (menu_items.c menu_step), OCT+ opens CALIBRATION / INFO / ABOUT, clears
 * LEARN; OCT- in INFO and ABOUT goes back to the list. HOME closes it, from them too; another button closes it and
 * acts (ui_input.c, as a held layer's lock) */
static void menu_move(int32_t s)                       /* KNOB 1: the next / previous row */
{
    uint32_t n = menu_nvis(), was = menu_pos(ui.menu_sel), k = (uint32_t)clamp((int32_t)was + (s > 0 ? 1 : -1), 0,
                                                                                 (int32_t)n - 1);
    ui.menu_sel = (uint8_t)menu_vis(k);
    ml_glide(was, k);
}
/* (Dah) OCT- held: the device's settings back to their defaults (the MENU's rows; not the project's, not 2ND CORE) */
static void menu_reset(void)
{
    static const uint8_t DEF[][2] = {{MI_HELP, 0}, {MI_COLOR, 3}, {MI_STYLE, 0}, {MI_LARGE, 0}, {MI_ANIM, 0}, {MI_LEDS, 2},
                                     {MI_SCROFF, 0}, {MI_HOME, 0}, {MI_HOLD, 1}, {MI_ACCEL, 0}, {MI_LATCH, 0},
                                     {MI_BPMLOCK, 0}, {MI_SCLLED, 0}, {MI_PREVIEW, 0}, {MI_CHADD, 1}, {MI_SELECT, 1},
                                     {MI_SNDPV, 0}, {MI_LOWCUT, 0}, {MI_USB, 0}, {MI_MFOLLOW, 0}, {MI_SCRWAKE, 0},
                                     {MI_SERIAL, 0}, {MI_RESTORE, 0}, {MI_SCOPE, 0}};
    uint32_t i;
    for (i = 0; i < NELEM(DEF); i++)
        menu_put(DEF[i][0], DEF[i][1]);
    ui_message("SETTINGS RESET");
    ui.force = 1;
}
static void menu_input(uint32_t oct)                  /* oct: ui_input.c oct_taps */
{
    static uint32_t rs_ms;
    if (ui.menu == 1 && ((fm1_in.buttons >> panel.btn[B_OCTDN]) & 1u)) {   /* (Dah) OCT- held: the settings reset */
        if (!rs_ms)
            rs_ms = fm1_ms | 1u;
        else if (rs_ms != 2u && (int32_t)(fm1_ms - rs_ms) >= 700) {
            menu_reset();
            rs_ms = 2u;
        }
    } else
        rs_ms = 0;
    int32_t s;
    uint32_t k, up = (oct >> 1) & 1u, dn = oct & 1u;
    if (ui.menu >= 2) {                                /* ABOUT: PRESETS scrolls (bounded); INFO, ABOUT: OCT- back to
                                                        * the tabs */
        if (dn)
            ui.menu = 1, ui.force = 1;
        else if (ui.menu == 2 && (s = panel_enc(EN_K1) + panel_enc(EN_SELECT)) != 0)   /* (Dah: KNOB 1, as the rows) */
            ui.menu_scroll = (uint16_t)clamp((int32_t)ui.menu_scroll + clamp(s, -128, 128) * 18, 0, menu_scroll_max());
        enc_drop();
        return;
    }
    if (MI_TAB[ui.menu_sel % MI_COUNT] >= MTAB_COUNT)  /* (a row the list does not show: its first) */
        ui.menu_sel = (uint8_t)menu_vis(0);
    if ((s = panel_enc(EN_K1)) != 0)                   /* (Dah) as SEQ's held menu: KNOB 1 the row, KNOB 2 its value */
        menu_move(s);
    s = panel_enc(EN_K2);
    (void)k;
    if (menu_valued(ui.menu_sel)) {
        /* a step (OCT+ the next value, OCT- the previous); COLOR previews the palette, STYLE is drawn so from the next
         * frame (FX LATCH: the latched effects are off while the menu is up) */
        s += (int32_t)up - (int32_t)dn;
        if (s)
            menu_put(ui.menu_sel, menu_step(ui.menu_sel, s));
    } else if (up) {
        if (ui.menu_sel == MI_LCLEAR) {                 /* LEARN CLEAR (1.5): every learned CC; no dialog (the menu has
                                                         * none: every other row's change is undone the same way) */
            ui_message(ml_clear_all() ? "LEARN CLEARED" : "NOTHING LEARNED");
        } else if (ui.menu_sel == MI_PANEL) {
            panel_setup();
            scrn.idle = fm1_ms;                         /* (SCREEN OFF: its own loop had the input) */
            ui.force = 1;
        } else if (ui.menu_sel == MI_FACTORY) {         /* FACTORY RESET: asked first (ui_input.c confirm_open) */
            menu_close();
            confirm_open(CF_FACTORY, 0);
        } else if (ui.menu_sel == MI_INFO) {
            ui.menu = 3;
            info.t = fm1_ms - INFO_CPU_MS;              /* (the CPU load read at once) */
            ui.force = 1;
        } else {                                       /* MI_ABOUT */
            ui.menu = 2;
            ui.menu_scroll = 0;
            ui.force = 1;
        }
    }
    enc_drop();                                        /* swallow the rest while the menu is up */
}
